function formatEvidenceBlock(evidence: ColdEvidence[]): string {
  return evidence
    .map(
      (e, i) =>
        `[${i + 1}] source=${e.source} role=${e.role}\n` +
        `title: ${e.title}\nurl: ${e.url}\nsnippet:\n${e.snippet}`
    )
    .join("\n\n");
}

